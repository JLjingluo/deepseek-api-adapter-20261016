static NSData *(*DSOriginalUserData)(id,SEL,NSString *);
static NSData *DSMigrateSyntheticUser(id self,SEL selector,NSString *key) {
    NSData *data=DSOriginalUserData(self,selector,key);
    if ([key isEqual:@"currentUser"] && [data isKindOfClass:NSData.class]) {
        id user=[NSJSONSerialization JSONObjectWithData:data options:0 error:NULL];
        if ([user isKindOfClass:NSDictionary.class] && [user[@"id"] isKindOfClass:NSString.class] && ![user[@"token"] isEqual:@"local-api-no-official-account"])
            [NSUserDefaults.standardUserDefaults setObject:user[@"id"] forKey:@"DSAPIAdapter.currentOfficialUserID"];
        if ([user isKindOfClass:NSDictionary.class] && [user[@"id"] isEqual:@"local-api"] && [user[@"token"] isEqual:@"local-api-no-official-account"]) {
            // Earlier experimental builds could persist a synthetic user through
            // the original bootstrap. It is not a valid official login token.
            SEL remove=NSSelectorFromString(@"removeValueForKey:");
            if ([self respondsToSelector:remove]) ((void (*)(id,SEL,id))objc_msgSend)(self,remove,key);
            [NSUserDefaults.standardUserDefaults setBool:YES forKey:@"DSAPIAdapter.removedLegacySyntheticUser"];
            return nil;
        }
    }
    return data;
}
static id (*DSOriginalSession)(id,SEL,NSURLSessionConfiguration *,id,NSOperationQueue *);
static long long (*DSOriginalLocalHash)(id,SEL,NSString *,long long,NSString *);
extern void DSInstallSettingsIntegration(void);
extern void DSInstallLocalSpeechUI(void);

static id DSCreateSession(id self, SEL selector, NSURLSessionConfiguration *configuration, id delegate, NSOperationQueue *queue) {
    NSURLSessionConfiguration *copy = [configuration copy];
    NSMutableArray *classes = [NSMutableArray arrayWithObjects:DSCompatibilityProtocol.class,DSGuestGuardProtocol.class,nil];
    for (Class cls in copy.protocolClasses ?: @[]) if (cls != DSCompatibilityProtocol.class && cls != DSGuestGuardProtocol.class) [classes addObject:cls];
    copy.protocolClasses = classes;
    id session=DSOriginalSession(self,selector,copy,delegate,queue);
    DSAPIInstallUploadBodyBridge(session);
    return session;
}
static long long DSLocalHash(id self, SEL selector, NSString *prefix, long long limit, NSString *target) {
    // This applies only to the handshake generated by our local URLProtocol.
    if ([prefix hasPrefix:@"local-api-handshake"]) return 0;
    return DSOriginalLocalHash(self,selector,prefix,limit,target);
}
static IMP DSReplace(Class cls, SEL selector, IMP replacement, const char *fallbackEncoding) {
    if (!cls) return NULL;
    Method method = class_getInstanceMethod(cls,selector);
    IMP previous = method ? method_getImplementation(method) : NULL;
    const char *encoding = method ? method_getTypeEncoding(method) : fallbackEncoding;
    if (!class_addMethod(cls,selector,replacement,encoding)) class_replaceMethod(cls,selector,replacement,encoding);
    return previous;
}
__attribute__((constructor)) static void DSInstall(void) {
    DSBootstrapMark("constructor-enter");
    NSString *executable = [NSBundle.mainBundle objectForInfoDictionaryKey:@"CFBundleExecutable"];
    NSString *version = [NSBundle.mainBundle objectForInfoDictionaryKey:@"CFBundleShortVersionString"];
    if (![executable isEqualToString:@"DeepSeek Chat"] || ![version isEqualToString:@"2.6.2"]) return;
    DSBootstrapMark("bundle-checked");
    Class mmkv=NSClassFromString(@"MMKV"); SEL readUser=NSSelectorFromString(@"getDataForKey:");
    if (class_getInstanceMethod(mmkv,readUser))
        DSOriginalUserData=(void *)DSReplace(mmkv,readUser,(IMP)DSMigrateSyntheticUser,"@@:@");
    Class meta = object_getClass(NSURLSession.class);
    DSOriginalSession = (void *)DSReplace(meta,@selector(sessionWithConfiguration:delegate:delegateQueue:),(IMP)DSCreateSession,"@@:@@@");
    DSBootstrapMark("url-session-hooked");
    [NSURLProtocol registerClass:DSCompatibilityProtocol.class];
    DSBootstrapMark("protocol-registered");
    DSInstallSettingsIntegration();
    DSInstallGuestIntegration();
    if (DSAPIIsEnabled()) DSInstallLocalSpeechUI();
    Class pow = NSClassFromString(@"PowCalculator");
    SEL hash = NSSelectorFromString(@"solveHash256:diff:target:");
    if (DSAPIIsEnabled() && pow && class_getClassMethod(pow,hash))
        DSOriginalLocalHash = (void *)DSReplace(object_getClass(pow),hash,(IMP)DSLocalHash,"q@:@q@");
    DSBootstrapMark("constructor-complete");
}
